    public static int SeedDraftProductTemplates(AppDbContext db, int? overrideSellerId = null, bool onlyIfNoneSeeded = true)
    {
        int sellerId = 0;
        if (overrideSellerId.HasValue && overrideSellerId.Value > 0 && db.Users.Any(u => u.Id == overrideSellerId.Value))
        {
            sellerId = overrideSellerId.Value;
        }
        else
        {
            var admin = db.Users.FirstOrDefault(u => u.Role == UserRoles.Admin);
            if (admin == null)
            {
                return 0;
            }
            sellerId = admin.Id;
        }

        var existingTitles = db.Listings
            .Select(l => l.Title)
            .ToHashSet(StringComparer.OrdinalIgnoreCase);

        if (onlyIfNoneSeeded && ProductTemplates.Any(t => existingTitles.Contains(t.Title)))
        {
            return 0;
        }

        var categories = db.Categories.ToList();
        if (!categories.Any())
        {
            return 0;
        }

        var rootServiceCategoryIds = categories
            .Where(c => c.ParentId == null && c.Name.Contains("Послуги", StringComparison.OrdinalIgnoreCase))
            .Select(c => c.Id)
            .ToHashSet();

        var nonServiceRoot = categories.FirstOrDefault(c => c.ParentId == null && !rootServiceCategoryIds.Contains(c.Id))
            ?? categories.First();

        var toAdd = new List<Listing>();
        var now = DateTime.UtcNow;

        for (int i = 0; i < ProductTemplates.Count; i++)
        {
            var tpl = ProductTemplates[i];
            if (existingTitles.Contains(tpl.Title))
            {
                continue;
            }

            var rootCat = categories.FirstOrDefault(c =>
                c.ParentId == null &&
                c.Name.Equals(tpl.RootCategoryName, StringComparison.OrdinalIgnoreCase));

            Category? targetCat = null;
            if (rootCat != null)
            {
                targetCat = categories.FirstOrDefault(c =>
                    c.ParentId == rootCat.Id &&
                    c.Name.Equals(tpl.SubcategoryName, StringComparison.OrdinalIgnoreCase))
                    ?? rootCat;
            }
            else
            {
                targetCat = categories.FirstOrDefault(c =>
                    c.Name.Equals(tpl.SubcategoryName, StringComparison.OrdinalIgnoreCase) &&
                    (!c.ParentId.HasValue || !rootServiceCategoryIds.Contains(c.ParentId.Value)))
                    ?? nonServiceRoot;
            }

            toAdd.Add(new Listing
            {
                Title = tpl.Title,
                Description = tpl.Description,
                Price = tpl.Price,
                ImageUrl = "/images/placeholder.svg",
                VideoUrl = null,
                CreatedAt = now.AddMinutes(-(ProductTemplates.Count - i)),
                CategoryId = targetCat.Id,
                SellerId = sellerId,
                Condition = tpl.Condition,
                Location = tpl.Location,
                IsShippingAvailable = tpl.IsShippingAvailable,
                Status = "Draft",
                IsFeatured = false,
                ViewsCount = 0
            });
            existingTitles.Add(tpl.Title);
        }

        if (toAdd.Count == 0)
        {
            return 0;
        }

        db.Listings.AddRange(toAdd);
        db.SaveChanges();
        return toAdd.Count;
    }
